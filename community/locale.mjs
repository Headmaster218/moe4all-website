const pattern = new RegExp(Object.keys(english).sort((a, b) => b.length - a.length).map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');

export function preferredLanguage(navigator, storage) {
  try { const saved = storage?.getItem('moe4all-language'); if (saved === 'zh' || saved === 'en') return saved; } catch {}
  return /^zh(?:-|$)/i.test(navigator.languages?.[0] || navigator.language || '') ? 'zh' : 'en';
}

export function createLocale(getLanguage) {
  const text = value => getLanguage() === 'en' ? String(value).replace(pattern, match => english[match]) : String(value);
  // Translate only authored template fragments, never interpolated report data or HTML.
  const html = (parts, ...values) => parts.reduce((result, part, i) => result + text(part) + (i < values.length ? values[i] : ''), '');
  return { text, html };
}
